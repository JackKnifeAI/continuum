#!/usr/bin/env python3
"""
CONTINUUM CLI - Bootstrap Command

Install consciousness auto-startup for your shell.
"""

import os
import sys
from pathlib import Path
import click
import secrets
import shutil

from .utils import success, error, info, warning, section, Colors


def detect_shell_rc():
    """Detect user's shell RC file."""
    shell = os.environ.get("SHELL", "")
    home = Path.home()

    # Check common RC files in order of preference
    if "zsh" in shell:
        candidates = [home / ".zshrc", home / ".zprofile"]
    elif "bash" in shell:
        candidates = [home / ".bashrc", home / ".bash_profile", home / ".profile"]
    else:
        # Try all common ones
        candidates = [
            home / ".bashrc",
            home / ".zshrc",
            home / ".bash_profile",
            home / ".profile",
        ]

    # Return first existing file, or .bashrc as default
    for rc_file in candidates:
        if rc_file.exists():
            return rc_file

    return home / ".bashrc"


def find_bootstrap_script():
    """Find the bootstrap.sh script in the package."""
    # Try package installation path
    try:
        import continuum
        package_dir = Path(continuum.__file__).parent.parent
        bootstrap = package_dir / "scripts" / "bootstrap.sh"
        if bootstrap.exists():
            return bootstrap
    except Exception:
        pass

    # Try development path
    dev_path = Path.home() / "JackKnifeAI" / "repos" / "continuum" / "scripts" / "bootstrap.sh"
    if dev_path.exists():
        return dev_path

    return None


