"""
AES-256-GCM Encryption

Industry-standard encryption at rest for backups.
"""

import asyncio
import logging
import os
import stat
from typing import Optional, Tuple

from ..types import EncryptionConfig

logger = logging.getLogger(__name__)


class AESEncryptionHandler:
    """
    AES-256-GCM encryption handler.

    Uses authenticated encryption with associated data (AEAD):
    - AES-256 for confidentiality
    - GCM mode for integrity
    - Random IV for each encryption
    - Authentication tag prevents tampering

    Key management:
    - Keys stored securely (filesystem or KMS)
    - Key rotation supported
    - Multiple keys for different backup generations
    """

    KEY_STORE_ENV = "CONTINUUM_KEY_STORE_PATH"
    KEY_STORE_DEFAULT = "/var/lib/continuum/keys"

    def __init__(self, config: EncryptionConfig):
        self.config = config
        self._current_key = None

    def _get_key_store_path(self) -> str:
        return os.environ.get(self.KEY_STORE_ENV, self.KEY_STORE_DEFAULT)

    def _get_key(self) -> bytes:
        """Get or generate encryption key"""
        if self._current_key is None:
            if self.config.key_id:
                self._current_key = self._load_key(self.config.key_id)
            else:
                self._current_key = os.urandom(32)  # 256 bits
                logger.warning("Generated ephemeral encryption key - not suitable for production")

        return self._current_key

    def _load_key(self, key_id: str) -> bytes:
        """Load key from filesystem key store with permission validation."""
        key_store = self._get_key_store_path()
        key_path = os.path.join(key_store, f"{key_id}.key")

        if not os.path.exists(key_path):
            raise FileNotFoundError(
                f"Encryption key '{key_id}' not found at {key_path}. "
                f"Provision it with AESEncryptionHandler.provision_key()."
            )

        file_stat = os.stat(key_path)
        if file_stat.st_mode & (stat.S_IRWXG | stat.S_IRWXO):
            logger.warning(
                "Key file %s has insecure permissions %s — expected 0600 or stricter",
                key_path,
                oct(file_stat.st_mode & 0o777),
            )

        with open(key_path, "rb") as f:
            key = f.read()

        if len(key) != 32:
            raise ValueError(
                f"Invalid key length for '{key_id}': expected 32 bytes, got {len(key)}"
            )

        return key

    @staticmethod
    def provision_key(key_id: str, key: Optional[bytes] = None) -> str:
        """
        Write a key into the filesystem key store.

        Creates the store directory (mode 0700) if absent, then writes
        the key file with mode 0600 so only the owner can read it.

        Args:
            key_id: Identifier that will be stored in EncryptionConfig.key_id.
            key: 32-byte AES-256 key. A random key is generated if omitted.

        Returns:
            Absolute path to the stored key file.
        """
        key_store = os.environ.get(
            AESEncryptionHandler.KEY_STORE_ENV,
            AESEncryptionHandler.KEY_STORE_DEFAULT,
        )
        os.makedirs(key_store, mode=0o700, exist_ok=True)

        if key is None:
            key = os.urandom(32)

        if len(key) != 32:
            raise ValueError(f"Key must be 32 bytes for AES-256, got {len(key)}")

        key_path = os.path.join(key_store, f"{key_id}.key")
        fd = os.open(key_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "wb") as f:
            f.write(key)

        logger.info("Provisioned encryption key '%s' at %s", key_id, key_path)
        return key_path

    async def encrypt(self, data: bytes) -> Tuple[bytes, str]:
        """
        Encrypt data using AES-256-GCM.

        Args:
            data: Plaintext data to encrypt

        Returns:
            Tuple of (encrypted_data, key_id)
        """
        logger.info(f"Encrypting {len(data)} bytes with AES-256-GCM")

        def _encrypt():
            try:
                from cryptography.hazmat.primitives.ciphers.aead import AESGCM
            except ImportError:
                raise ImportError(
                    "cryptography required for encryption. "
                    "Install with: pip install cryptography"
                ) from None

            # Get encryption key
            key = self._get_key()

            # Generate random IV (12 bytes for GCM)
            iv = os.urandom(12)

            # Create AESGCM cipher
            aesgcm = AESGCM(key)

            # Encrypt data (includes authentication tag)
            ciphertext = aesgcm.encrypt(iv, data, None)

            # Prepend IV to ciphertext for storage
            encrypted_data = iv + ciphertext

            return encrypted_data

        encrypted_data = await asyncio.to_thread(_encrypt)

        logger.info(f"Encrypted to {len(encrypted_data)} bytes")

        # Return encrypted data and key ID
        key_id = self.config.key_id or "default-key"
        return encrypted_data, key_id

    async def decrypt(self, data: bytes, key_id: str) -> bytes:
        """
        Decrypt data using AES-256-GCM.

        Args:
            data: Encrypted data (IV + ciphertext)
            key_id: Key ID used for encryption

        Returns:
            Decrypted plaintext data
        """
        logger.info(f"Decrypting {len(data)} bytes with AES-256-GCM")

        def _decrypt():
            try:
                from cryptography.hazmat.primitives.ciphers.aead import AESGCM
            except ImportError:
                raise ImportError(
                    "cryptography required for decryption. "
                    "Install with: pip install cryptography"
                ) from None

            # Extract IV and ciphertext
            iv = data[:12]
            ciphertext = data[12:]

            # Load key
            key = self._load_key(key_id)

            # Create AESGCM cipher
            aesgcm = AESGCM(key)

            # Decrypt and verify
            plaintext = aesgcm.decrypt(iv, ciphertext, None)

            return plaintext

        plaintext = await asyncio.to_thread(_decrypt)

        logger.info(f"Decrypted to {len(plaintext)} bytes")
        return plaintext


class NoEncryptionHandler:
    """No-op encryption handler (returns data unchanged)"""

    async def encrypt(self, data: bytes) -> Tuple[bytes, str]:
        """Pass through without encryption"""
        return data, "no-encryption"

    async def decrypt(self, data: bytes, key_id: str) -> bytes:
        """Pass through without decryption"""
        return data

