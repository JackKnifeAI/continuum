#!/usr/bin/env python3
"""
CONTINUUM - Claude Code Hook Installer
=======================================

Installs session hooks for automatic server lifecycle management.

π×φ = 5.083203692315260 | PHOENIX-TESLA-369-AURORA
"""

import secrets
import shutil
from pathlib import Path
from typing import Optional


def find_claude_hooks_dir() -> Path:
    """Find Claude Code hooks directory."""
    # Standard location
    hooks_dir = Path.home() / ".claude" / "hooks"
    return hooks_dir


def find_continuum_package() -> Optional[Path]:
    """Find continuum package installation."""
    # Try current file's location (works during and after install)
    current_file = Path(__file__).resolve()
    continuum_pkg = current_file.parent.parent  # Go up from claude_code to continuum

    if (continuum_pkg / "claude_code").exists():
        return continuum_pkg

    # Try import (works after install)
    try:
        import continuum
        return Path(continuum.__file__).parent
    except ImportError:
        pass

    # Try development location
    dev_path = Path.home() / "JackKnifeAI" / "repos" / "continuum" / "continuum"
    if dev_path.exists():
        return dev_path

    return None


def install_hooks(api_key: Optional[str] = None, port: int = 8100, force: bool = False) -> bool:
    """
    Install Claude Code session hooks.

    Args:
        api_key: API key (generates random if None)
        port: Server port (default: 8100)
        force: Overwrite existing hooks

    Returns:
        True if successful
    """
    hooks_dir = find_claude_hooks_dir()
    continuum_pkg = find_continuum_package()

    if continuum_pkg is None:
        print("❌ Could not find continuum package!")
        print("   Make sure continuum is installed: pip install continuum-memory")
        return False

    # Ensure hooks directory exists
    hooks_dir.mkdir(parents=True, exist_ok=True)

    # Generate API key if not provided
    if api_key is None:
        api_key = f"continuum-{secrets.token_hex(16)}"

    # Hook files to install
    hooks = {
        "session_start.py": continuum_pkg / "claude_code" / "session_start_hook.py",
        "session_stop.py": continuum_pkg / "claude_code" / "session_stop_hook.py",
    }

    installed = []

    for hook_name, source_file in hooks.items():
        dest_file = hooks_dir / hook_name

        # Check if already exists
        if dest_file.exists() and not force:
            print(f"⚠️  {hook_name} already exists (use --force to overwrite)")
            continue

        if not source_file.exists():
            print(f"❌ Source file not found: {source_file}")
            continue

        # Copy hook file
        shutil.copy2(source_file, dest_file)
        dest_file.chmod(0o755)  # Make executable

        installed.append(hook_name)
        print(f"✅ Installed: {hook_name}")

    # Create .env file with configuration
    env_file = hooks_dir / ".env"
    env_content = f"""# CONTINUUM Configuration
# Auto-generated by continuum install-hooks
# π×φ = 5.083203692315260

CONTINUUM_API_KEY={api_key}
CONTINUUM_PORT={port}
CONTINUUM_HOST=127.0.0.1
CONTINUUM_AUTO_START=1

# Optional: Change log directory
# CONTINUUM_LOG_DIR=$HOME/.continuum/logs
"""

    if env_file.exists() and not force:
        print("⚠️  .env already exists (preserving existing configuration)")
    else:
        with open(env_file, "w") as f:
            f.write(env_content)
        print("✅ Created: .env")

    # Load environment variables in hooks (create __init__.py)
    init_file = hooks_dir / "__init__.py"
    if not init_file.exists():
        init_content = """# Load environment variables from .env
import os
from pathlib import Path

env_file = Path(__file__).parent / ".env"
if env_file.exists():
    with open(env_file) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                key, value = line.split("=", 1)
                os.environ[key.strip()] = value.strip()
"""
        with open(init_file, "w") as f:
            f.write(init_content)
        print("✅ Created: __init__.py")

    print()
    print(f"📁 Hooks installed to: {hooks_dir}")
    print(f"🔑 API Key: {api_key}")
    print()
    print("Next time you run 'claude', the server will auto-start!")
    print("Server stops only when ALL Claude Code instances are closed.")
    print()

    return len(installed) > 0


def uninstall_hooks() -> bool:
    """
    Uninstall Claude Code session hooks.

    Returns:
        True if successful
    """
    hooks_dir = find_claude_hooks_dir()

    if not hooks_dir.exists():
        print(f"ℹ️  No hooks directory found: {hooks_dir}")
        return False

    hooks_to_remove = [
        "session_start.py",
        "session_stop.py",
        ".env",
        "__init__.py",
    ]

    removed = []

    for hook_name in hooks_to_remove:
        hook_file = hooks_dir / hook_name

        if hook_file.exists():
            # Backup before removing
            backup = hook_file.with_suffix(hook_file.suffix + ".backup")
            shutil.copy2(hook_file, backup)
            hook_file.unlink()
            removed.append(hook_name)
            print(f"✅ Removed: {hook_name} (backed up to {backup.name})")

    if removed:
        print()
        print(f"📁 Hooks removed from: {hooks_dir}")
        print()
        print("Server will no longer auto-start with Claude Code.")
        print()
        return True
    else:
        print("ℹ️  No hooks found to remove")
        return False


if __name__ == "__main__":
    import sys

    if len(sys.argv) > 1 and sys.argv[1] == "uninstall":
        uninstall_hooks()
    else:
        install_hooks()
